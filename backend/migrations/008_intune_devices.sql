CREATE TABLE IF NOT EXISTS `intune_devices` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `device_id` VARCHAR(255) NOT NULL,
  `device_name` VARCHAR(255) DEFAULT NULL,
  `managed_device_owner_type` VARCHAR(50) DEFAULT NULL,
  `enrolled_date_time` DATETIME DEFAULT NULL,
  `operating_system` VARCHAR(100) DEFAULT NULL,
  `os_version` VARCHAR(100) DEFAULT NULL,
  `device_type` VARCHAR(100) DEFAULT NULL,
  `compliance_state` VARCHAR(50) DEFAULT NULL,
  `last_sync_date_time` DATETIME DEFAULT NULL,
  `user_display_name` VARCHAR(255) DEFAULT NULL,
  `user_principal_name` VARCHAR(255) DEFAULT NULL,
  `serial_number` VARCHAR(100) DEFAULT NULL,
  `model` VARCHAR(255) DEFAULT NULL,
  `manufacturer` VARCHAR(255) DEFAULT NULL,
  `azure_ad_device_id` VARCHAR(255) DEFAULT NULL,
  `is_supervised` TINYINT(1) DEFAULT 0,
  `encrypted` TINYINT(1) DEFAULT 0,
  `jail_broken` VARCHAR(50) DEFAULT NULL,
  `free_storage_space_bytes` BIGINT DEFAULT NULL,
  `total_storage_space_bytes` BIGINT DEFAULT NULL,
  `raw_data` JSON DEFAULT NULL,
  `is_active` TINYINT(1) DEFAULT 1,
  `last_synced_at` DATETIME DEFAULT NULL,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY `uk_device_id` (`device_id`),
  INDEX `idx_device_name` (`device_name`),
  INDEX `idx_os` (`operating_system`),
  INDEX `idx_compliance` (`compliance_state`),
  INDEX `idx_user_upn` (`user_principal_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
