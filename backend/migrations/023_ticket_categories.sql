-- Ticket category tree (two levels: category -> subcategory). Global, shared by all customers.
-- Tickets keep storing the category/subcategory NAME in tickets.category / tickets.subcategory,
-- so existing reports and filters keep working. applies_to lists the ticket types a root serves.
CREATE TABLE IF NOT EXISTS `ticket_categories` (
  `id` INT PRIMARY KEY,
  `parent_id` INT DEFAULT NULL,
  `name` VARCHAR(100) NOT NULL,
  `applies_to` VARCHAR(100) DEFAULT NULL,
  `sort_order` INT NOT NULL DEFAULT 0,
  `is_active` TINYINT(1) NOT NULL DEFAULT 1,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX `idx_tc_parent` (`parent_id`),
  INDEX `idx_tc_active` (`is_active`),
  FOREIGN KEY (`parent_id`) REFERENCES `ticket_categories`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

