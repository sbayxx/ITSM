// yw_categories.icon is seeded with emoji; map them to icon names so the
// database can keep its emoji while the UI renders line icons.
const emojiIcons = {
  '🔍': 'file-search',
  '👥': 'users',
  '🔒': 'lock',
  '🔧': 'wrench',
  '🎓': 'graduation-cap',
  '💰': 'coins',
  '✅': 'check-circle',
}

export function resolveIconName(value) {
  if (!value) return 'circle'
  if (emojiIcons[value]) return emojiIcons[value]
  if (icons[value]) return value
  return 'circle'
}
